// Local Supabase stack in Docker, filled from a private-output backup. Never touches production.
//
//   node scripts/local-stack.mjs up                 start containers, write .env.docker.local
//   node scripts/local-stack.mjs restore [dir]      wipe local DB, apply migrations, restore backup
//   node scripts/local-stack.mjs dev                next dev against the local stack
//   node scripts/local-stack.mjs down               stop containers (data is kept)
//   node scripts/local-stack.mjs status             show local URLs
//
// Every command that writes data checks the target URL is localhost first.

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const ENV_FILE = ".env.docker.local";
const LOCAL_HOSTS = new Set(["127.0.0.1", "localhost"]);

function run(cmd, args, opts = {}) {
  const res = spawnSync(cmd, args, { stdio: "inherit", shell: process.platform === "win32", ...opts });
  if (res.status !== 0) {
    console.error(`\n[ERROR] Perintah gagal: ${cmd} ${args.join(" ")}`);
    process.exit(res.status ?? 1);
  }
  return res;
}

function assertLocal(url) {
  let host = "";
  try {
    host = new URL(url).hostname;
  } catch {
    // fall through
  }
  if (!LOCAL_HOSTS.has(host)) {
    console.error(`[ERROR] Target bukan lokal (${url}). Dibatalkan agar produksi tidak tersentuh.`);
    process.exit(1);
  }
}

function readStatus() {
  const res = spawnSync("npx", ["supabase", "status", "-o", "json"], {
    encoding: "utf8",
    shell: process.platform === "win32",
  });
  if (res.status !== 0) return null;
  const start = res.stdout.indexOf("{");
  if (start === -1) return null;
  try {
    return JSON.parse(res.stdout.slice(start));
  } catch {
    return null;
  }
}

function writeEnvFile() {
  const s = readStatus();
  if (!s?.API_URL) {
    console.error("[ERROR] Stack lokal belum berjalan. Jalankan: npm run local:up");
    process.exit(1);
  }
  const env = {
    NEXT_PUBLIC_SUPABASE_URL: s.API_URL,
    NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: s.PUBLISHABLE_KEY || s.ANON_KEY,
    SUPABASE_SERVICE_ROLE_KEY: s.SERVICE_ROLE_KEY || s.SECRET_KEY,
  };
  assertLocal(env.NEXT_PUBLIC_SUPABASE_URL);
  const body = [
    "# Generated by scripts/local-stack.mjs: local Docker Supabase only. Safe to delete.",
    ...Object.entries(env).map(([k, v]) => `${k}=${v}`),
    "",
  ].join("\n");
  fs.writeFileSync(ENV_FILE, body);
  return { env, studio: s.STUDIO_URL };
}

function loadEnvFile() {
  if (!fs.existsSync(ENV_FILE)) return writeEnvFile().env;
  const env = {};
  for (const line of fs.readFileSync(ENV_FILE, "utf8").split(/\r?\n/)) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (m) env[m[1]] = m[2];
  }
  assertLocal(env.NEXT_PUBLIC_SUPABASE_URL);
  return env;
}

const [command, arg] = process.argv.slice(2);

switch (command) {
  case "up": {
    run("npx", ["supabase", "start"]);
    const { studio } = writeEnvFile();
    console.log(`\nStack lokal siap. Kunci ditulis ke ${ENV_FILE}. Studio: ${studio ?? "http://127.0.0.1:54323"}`);
    break;
  }
  case "restore": {
    const backupDir = arg ? path.resolve(arg) : null;
    if (!backupDir || !fs.existsSync(path.join(backupDir, "manifest.json"))) {
      console.error(`[ERROR] Folder backup tidak valid: ${arg ?? "(kosong)"}`);
      process.exit(1);
    }
    const env = writeEnvFile().env;
    console.log("Mengosongkan DB lokal dan menerapkan ulang migrasi ...");
    run("npx", ["supabase", "db", "reset", "--local", "--no-seed"]);
    // Process env wins over .env inside restore.mjs, so it can only reach the local stack.
    run("node", ["scripts/restore.mjs", backupDir, "--yes"], { env: { ...process.env, ...env } });
    break;
  }
  case "dev": {
    const env = loadEnvFile();
    console.log(`next dev -> ${env.NEXT_PUBLIC_SUPABASE_URL} (lokal)`);
    // Next.js never overrides variables already in process.env, so .env (prod) is ignored for these keys.
    run("npx", ["next", "dev"], { env: { ...process.env, ...env } });
    break;
  }
  case "down":
    run("npx", ["supabase", "stop"]);
    break;
  case "status":
    run("npx", ["supabase", "status"]);
    break;
  default:
    console.log("Pakai: node scripts/local-stack.mjs <up|restore <folder>|dev|down|status>");
    process.exit(command ? 1 : 0);
}
